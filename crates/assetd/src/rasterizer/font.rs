/// Render an ASCII string onto an RGBA canvas at `(start_x, start_y)`.
/// Each character is 5 pixels wide and 7 pixels high, followed by 1 pixel spacing.
pub fn render_text(
    image: &mut RgbaImage,
    start_x: u32,
    start_y: u32,
    text: &str,
    color: [u8; 4],
) {
    let mut cur_x = start_x;
    for b in text.bytes() {
        if !(32..=126).contains(&b) {
            cur_x += 6;
            continue;
        }
        let glyph = FONT_5X7[(b - 32) as usize];
        for (col, col_bits) in glyph.iter().enumerate() {
            for row in 0..7 {
                if (col_bits >> row) & 1 == 1 {
                    let px = cur_x + col as u32;
                    let py = start_y + row as u32;
                    if px < image.width() && py < image.height() {
                        image.put_pixel(px, py, Rgba(color));
                    }
                }
            }
        }
        cur_x += 6;
    }
}
